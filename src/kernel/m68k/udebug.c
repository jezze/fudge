static void drawglyph(unsigned char c)
{

    unsigned char *glyph = glyphs[(c >= 0x20 && c < 0x20 + GLYPHS) ? c - 0x20 : '?' - 0x20];
    unsigned int y;

    for (y = 0; y < GLYPHHEIGHT; y++)
        plane[(row * GLYPHHEIGHT + y) * SCREEN_ROWBYTES + column] = glyph[y];

}

static void newline(void)
{

    column = 0;

    if (row + 1 < SCREEN_ROWS)
    {

        row++;

    }

    else
    {

        buffer_copy(plane, plane + GLYPHHEIGHT * SCREEN_ROWBYTES, (SCREEN_ROWS - 1) * GLYPHHEIGHT * SCREEN_ROWBYTES);
        buffer_clear(plane + (SCREEN_ROWS - 1) * GLYPHHEIGHT * SCREEN_ROWBYTES, GLYPHHEIGHT * SCREEN_ROWBYTES);

    }

}

/* paula's serial port takes a character with its stop bit in SERDAT once SERDATR says the buffer is empty; the screen shows the same until amiga-video takes the display */
static void print(unsigned int count, char *buffer)
{

    unsigned int i;

    for (i = 0; i < count; i++)
    {

        while (!(custom[0x18 / 2] & 0x2000));

        custom[0x30 / 2] = 0x100 | (unsigned char)buffer[i];

        if (buffer[i] == '\n')
        {

            newline();

        }

        else
        {

            if (column == SCREEN_COLUMNS)
                newline();

            drawglyph(buffer[i]);

            column++;

        }

    }

}

/* one hires bitplane (FMODE 0), its pointer reset by a copper list every frame */
static void setupscreen(void)
{

    unsigned short *copper = (unsigned short *)SCREEN_COPPER;

    buffer_clear(plane, SCREEN_ROWBYTES * SCREEN_HEIGHT);

    copper[0] = REG_BPL1PTH;
    copper[1] = SCREEN_PLANE >> 16;
    copper[2] = REG_BPL1PTL;
    copper[3] = SCREEN_PLANE & 0xFFFF;
    copper[4] = 0xFFFF;
    copper[5] = 0xFFFE;
    custom[REG_DMACON / 2] = 0x7FFF;
    custom[REG_FMODE / 2] = 0;
    custom[REG_BPLCON0 / 2] = 0x9200;
    custom[REG_BPLCON1 / 2] = 0;
    custom[REG_BPLCON2 / 2] = 0;
    custom[REG_BPLCON3 / 2] = 0x0C00;
    custom[REG_BPLCON4 / 2] = 0x0011;
    custom[REG_BPL1MOD / 2] = 0;
    custom[REG_DIWSTRT / 2] = 0x2C81;
    custom[REG_DIWSTOP / 2] = 0x2CC1;
    custom[REG_DDFSTRT / 2] = 0x003C;
    custom[REG_DDFSTOP / 2] = 0x00D4;
    custom[REG_COLOR01 / 2] = 0x0FFF;
    custom[REG_COP1LCH / 2] = SCREEN_COPPER >> 16;
    custom[REG_COP1LCL / 2] = SCREEN_COPPER & 0xFFFF;
    custom[REG_COPJMP1 / 2] = 0;
    custom[REG_DMACON / 2] = 0x8000 | 0x0200 | 0x0100 | 0x0080;

}

/* the background tells how far the boot got when nothing is printed */
