static void drawcell(unsigned int offset)
{

    unsigned char c = cells[offset];
    unsigned char *glyph = glyphs[(c >= 0x20 && c < 0x20 + GLYPHS) ? c - 0x20 : '?' - 0x20];
    unsigned int foreground = palette[cells[offset + 1] & 0x0F];
    unsigned int background = palette[cells[offset + 1] >> 4];
    unsigned char *start = pixels + ((offset / COLSIZE) * GLYPHHEIGHT) * pitch + ((offset % COLSIZE) / 2) * GLYPHWIDTH * bpp;
    unsigned int y;

    for (y = 0; y < GLYPHHEIGHT; y++)
    {

        unsigned char *pixel = start + y * pitch;
        unsigned int x;

        for (x = 0; x < GLYPHWIDTH; x++)
        {

            unsigned int color = (glyph[y] & (0x80 >> x)) ? foreground : background;
            unsigned int value = (((color >> 16) & 0xFF) << redshift) | (((color >> 8) & 0xFF) << greenshift) | ((color & 0xFF) << blueshift);

            pixel[0] = value;
            pixel[1] = value >> 8;
            pixel[2] = value >> 16;

            if (bpp == 4)
                pixel[3] = value >> 24;
            pixel += bpp;

        }

    }

}

static void output(unsigned int offset)
{

    if (pixels)
    {

        drawcell(offset);

    }

    else
    {

        framebuffer[offset] = cells[offset];
        framebuffer[offset + 1] = cells[offset + 1];

    }

}
static struct debug_interface debug;
static unsigned int udebug_offset = 0;
static unsigned int udebug_count = 0;

static void print(unsigned int count, char *buffer, unsigned char color)
{

    unsigned int i;

    for (i = 0; i < count; i++)
    {

        if (buffer[i] == '\n')
        {

            udebug_offset = (udebug_offset + COLSIZE) - udebug_offset % COLSIZE;

        }

        else
        {

            cells[udebug_offset] = buffer[i];
            cells[udebug_offset + 1] = color;

            output(udebug_offset);

            udebug_offset += 2;

        }

        if (udebug_offset >= TOTAL)
        {

            unsigned int offset;

            buffer_copy(cells, cells + COLSIZE, TOTAL - COLSIZE);
            buffer_clear(cells + TOTAL - COLSIZE, COLSIZE);

            for (offset = 0; offset < TOTAL; offset += 2)
                output(offset);

            udebug_offset = TOTAL - COLSIZE;

        }

    }

}

static void debug_write(unsigned int level, unsigned int count, char *buffer, char *file, unsigned int line)
{

    if (level)
    {

        char num[32];

        print(cstring_write_value(num, 32, udebug_count, 16, 8, 0), num, 0x03);
        print(1, " ", 0x08);
        print(cstring_length(file), file, 0x0D);
        print(1, ":", 0x0F);
        print(cstring_write_value(num, 32, line, 10, 0, 0), num, 0x0D);
        print(1, "\n", 0x08);

        switch (level)
        {

        case DEBUG_CRITICAL:
            print(8, "CRITICAL", 0x40);

            break;

        case DEBUG_ERROR:
            print(8, "   ERROR", 0x40);

            break;

        case DEBUG_WARNING:
            print(8, " WARNING", 0xE0);

            break;

        case DEBUG_INFO:
            print(8, "    INFO", 0x20);

            break;

        }

        print(1, " ", 0x08);
        print(count, buffer, 0x0F);
        print(1, "\n", 0x08);

        udebug_count++;

    }

    else
    {

        print(9, "     ... ", 0x08);
        print(count, buffer, 0x07);
        print(1, "\n", 0x08);

    }

}

void udebug_setframebuffer(void *address, unsigned int framebufferpitch, unsigned int framebufferbpp, unsigned int redposition, unsigned int greenposition, unsigned int blueposition)
{

    unsigned int offset;

    pixels = address;
    pitch = framebufferpitch;
    bpp = framebufferbpp;
    redshift = redposition;
    greenshift = greenposition;
    blueshift = blueposition;

    for (offset = 0; offset < TOTAL; offset += 2)
        output(offset);

}

